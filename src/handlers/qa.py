def handle(msg: str,
           faq_retriever: FAQRetriever | None = None,
           rag_retriever: BM25Retriever | None = None,
           llm: MinMaxClient | None = None,
           facts: list[Fact] | None = None) -> dict:
    faq_retriever = faq_retriever or FAQRetriever.from_default()
    llm = llm or MinMaxClient.from_env()
    # facts 传 None 表示"去读事实表"。传空列表是**测试用的隔离手段**
    # (跑测试时不该受助教本机那份 课程事务.txt 影响,见 conftest 的同名 fixture)。
    facts = load_facts() if facts is None else facts

    faq_hits = faq_retriever.search(msg, top_k=3)
    faq_hit = bool(faq_hits) and faq_hits[0]["score"] >= config.FAQ_HIT_THRESHOLD
    kind = _classify(msg)

    # ─── 现行事务口径(只在事务档注入)────────────────────────────
    # 为什么**不**等"FAQ 没命中"才注入:实测事务题绝大多数都命中 FAQ
    # (旧数写的 90.3% 是拿被单测污染的日志算的,见 course_facts 顶部的勘误;
    #  干净数据只剩 22 条问句,样本太小,但方向一致),
    # 只在未命中时注入等于只覆盖 10% 的情况,而真正的风险恰恰在命中的那 90% ——
    # FAQ 条目不会过期,截止时间改了这一条旧答案照样被命中、还说得很自信。
    # 所以只要判成事务档就把现行事实放进去,并且**放在 FAQ 前面**,
    # 让"以它为准"这条规则有顺序上的支撑。
    facts_block = render_facts(facts) if (facts and kind == "admin") else ""

    # ─── 诊断信息:检索做完之后一次性落盘 ────────────────────────
    # 2026-09-20 补的。原来只有 `qa_kind`(message/kind/faq_hit)和 `reply`(只记长度),
    # 于是**看得出"哪句没命中 FAQ",看不出"哪句检索得烂"** —— 而后者才是
    # 语料/锚点该往哪儿补的依据。
    # 字段合并进同一条事件(而不是新开一条):挖矿脚本要同时知道
    # "问的是什么 / 走哪条通路 / 召回了什么 / 分多高",拆成两条后得靠时间戳对齐,
    # 同一秒内的两条会串。代价是这条事件变长了一点,值。
    diag: dict = {
        "message": msg[:120],
        "kind": kind,
        "faq_hit": faq_hit,
        "faq_top": round(faq_hits[0]["score"], 3) if faq_hits else None,
        "n_facts": len(facts),
        "facts_used": bool(facts_block),
    }
    rag_hits: list[dict] = []

    facts_src = ["课程事务(现行)"] if facts_block else []
    # 从 facts_src 起手:万一用上了现行口径、资料却一块都没召回到,
    # 答复末尾的「参考:」也得把它写出来 —— 用了它却瞒着,助教就查不出
    # "这句话是照哪条事实说的"(事务类答复最需要能追溯)。
    sources: list[str] = list(facts_src)

    if kind == "admin" and faq_hit:
        # 1) 事务类 + FAQ 命中:**不查资料**,FAQ 是依据,交给大模型润色成一句人话
        #    (这条快路只服务事务题 —— 概念题要能展开讲解,不能被短路)
        #    有现行事实时事实排在最前,见上面 facts_block 的说明。
        #
        # 【勘误 2026-09-20】这里原来的注释写"直接答,**不调大模型**",
        # 但这段并没有 return,下面照样会调 —— 代码和注释说的是两回事(实测 llm.log 每次 +1)。
        # 到底该补 return 还是该改注释?**量过再定的**,不是拍脑袋:
        #   28 条能自命中的事务类 FAQ 逐条走真实通路,比对"FAQ 原文里的数字"和"答复里的数字"。
        #   结果(实测,`scripts/eval_admin_fidelity.py`):
        #     **FAQ 有、答复里没有 = 0 条**  ← 这才是失真,它是 0,所以润色不会丢事实
        #     答复里多出数字 = 18 条,逐条看了上下文,分三类,没有一类是"FAQ 的数字被改错":
        #       ① 同义换算/写法归正:零→0、"一周"→"七天"、"十"→10
        #       ② 中文数字当普通字用:一下 / 一起 / 对不上(误报,本来就不是数字)
        #       ③ 模型自己补的常识:如"A4 纸"、举例"10.46 怎么做"
        #   ⚠️ 所以别把结论写成"数字原样不动" —— **会被换写法**。准确的说法是:
        #      **不丢信息**(28/28),但**会增补**,而增补的东西不受助教口径控制(见第 ③ 类)。
        # 保留调用的理由:换来了更自然的措辞,还能把第 2 条同义 FAQ 一并合进来,而代价是不可观测级别。
        # 只把注释改对 —— 免得以后有人照着旧注释"修"出一个事务答复直接裸奔的快路。
        # 复现:`scripts/eval_admin_fidelity.py`(会真的调 API,不进单测)。
        diag["path"] = "faq"
        faq_ctx, faq_src = _faq_context(faq_hits)
        # 现行事实放在 FAQ **前面**:提示词里"冲突时以【课程事务(现行)】为准"
        # 这条规则,需要有顺序上的支撑才不会变成一句空话。
        context = f"{facts_block}\n\n{faq_ctx}" if facts_block else faq_ctx
        sources = facts_src + faq_src
    else:
        # 2) 其余情况都先查资料
        diag["path"] = "rag"
        rag_retriever = rag_retriever or _try_load_rag()
        if rag_retriever is None:
            # 索引没建也算一条可统计的事件:日志里能直接看出"有几次是没索引答的"
            diag["path"] = "no_index"
            log_event("qa_kind", **diag)
            return {
                "type": "question",
                "reply": "抱歉,知识库尚未构建。请先运行 `python scripts/build_index.py`。",
                "sources": [],
            }
        rag_hits = rag_retriever.search(msg, top_k=config.RAG_TOP_K)

        blocks: list[str] = []
        if facts_block:
            blocks.append(facts_block)
        if rag_hits:
            blocks.append("【课程资料】\n" + "\n\n---\n\n".join(
                f"【来源:{h['source']}】\n{h['text']}" for h in rag_hits
            ))
            # 用 dict.fromkeys 而不是 set:集合的迭代顺序取决于字符串哈希,而 Python
            # 默认**每个进程的哈希种子是随机的** —— 同一句话两次运行,答复末尾
            # 「参考:」里的文件顺序会不一样。那会让"同一问题两次答复不一致"无法复现、
            # 也没法拿答复做快照测试。dict.fromkeys 去重的同时**保住 rag_hits 的得分降序**,
            # 于是最相关的文件天然排在最前面(也正是学生最该先翻的那份)。
            sources = list(dict.fromkeys(facts_src + [h["source"] for h in rag_hits]))
        # 3) 概念题:FAQ 命中**不是短路,而是加成** —— 常问问题里往往有老师/助教
        #    给过的说法,当补充材料喂给模型,让它"在权威说法之上讲得更透"。
        #    题目类不加 FAQ:问 1.36 时那条"作业怎么提交"纯属噪声,只会误导。
        if faq_hit and kind != "problem":
            fctx, fsrc = _faq_context(faq_hits)
            blocks.append("【常问问题】\n" + fctx)
            sources = list(dict.fromkeys(sources + fsrc))
        context = "\n\n".join(blocks) if blocks else "(无相关资料)"

    # 检索诊断一并落盘(此时 sources / rag_hits 都已定稿)。
    # `top_score` 是"这句问得准不准"的量化信号:top 很低说明库里大概率没有对应内容,
    # 那就是该补语料或补 FAQ 的地方 —— 挖矿脚本正是按它排序的。
    diag["n_hits"] = len(rag_hits)
    diag["top_score"] = round(rag_hits[0]["score"], 3) if rag_hits else None
    diag["sources"] = sources
    log_event("qa_kind", **diag)

    user_prompt = (
        f"【学生问题】\n{msg}\n\n"
        f"【相关资料】\n{context}\n\n"
        "【你的回答】"
    )
    reply = llm.chat(_SYSTEM_PROMPT, user_prompt, temperature=0.3)
    if not reply:
        # LLM 失败时退化:直接把最相关片段当回复
        reply = "(LLM 暂不可用,以下是相关资料原文)\n" + context[:500]

    if sources:
        reply += f"\n\n参考:{', '.join(sources)}"
    return {"type": "question", "reply": reply, "sources": sources}


def _faq_context(faq_hits: list[dict]) -> tuple[str, list[str]]:
    """把 FAQ 命中转成喂给 LLM 的上下文。取前 2 条(第 2 条有时是同义问法)。"""
    context = "\n\n".join(
        f"Q: {h['question']}\nA: {h['answer']}" for h in faq_hits[:2]
    )
    return context, ["FAQ(常问问题.txt)"]


def _try_load_rag() -> BM25Retriever | None:
    try:
        return BM25Retriever.load(config.BM25_INDEX_PATH)
    except FileNotFoundError:
        return None
