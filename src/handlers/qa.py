# ─── 带题号的提问要**先查资料** ───────────────────────────────────
# 2026-09-20 实测踩到的坑:学生问「电路基础第一章作业的1.36怎么做？」,
# FAQ 里那条「电路基础理论的作业怎么提交？要交给学委吗？」以 5.61 分(阈值 4.0)命中,
# 于是**短路掉了资料通路** —— 学生拿到的是一份"作业在雨课堂提交"的流程说明,
# 外加一句"这个我不确定"。而 1.36 的答案明明就在知识库里(检索得分 12.96,排第 4)。
#
# 根因是 FAQ 通路的设计前提「FAQ 命中就不必查资料」在**具体题目**上不成立:
# 「电路基础 + 作业 + 怎么做」这几个词既属于"怎么交作业",也属于"这题怎么做",
# 而实词闸门拦不住它(共享的是 电路/基础/作业/怎么,都是实词)。
#
# 所以规则改成:**提问里带题号 → 认定问的是具体题目 → 先查资料,FAQ 只兜底**;
# 不带题号的问题走原来的"FAQ 优先"不变。这样
#   「作业怎么提交」      → 仍走 FAQ(没有题号)
#   「1.36 怎么做」       → 走资料(有题号)
#   「1.23 最后算电还是电费」→ 走资料,拿到完整解答(比原来那条窄 FAQ 更好)
_PROBLEM_REF = re.compile(
    r"\d{1,2}\s*[.．]\s*\d{1,3}"          # 1.36 / 10.46
    r"|第\s*\d{1,3}\s*题"                  # 第5题
    r"|题\s*\d{1,2}\s*[.．]\s*\d{1,3}"     # 题10.46
)


def _is_problem_query(msg: str) -> bool:
    return bool(_PROBLEM_REF.search(msg))


# ─── 提问分档:问题目 / 问事务 / 问概念(2026-09-20 晚加) ────────────
#
# 起因:学生问「什么是叠加原理」,知识库里只有**作业答案**、没有教材正文,
# 于是资料查不到 → 模型按旧提示词回「这个我不确定,建议问任课老师」。
# 助教反馈:这种**学科概念题**应当让大模型用自己的知识讲清楚,并且尽量
# 结合库里那些作业题,帮学生把概念和作业对上。只有**课程事务**类问题
# 才必须严格"资料里没有就说不知道"。
#
# 注意分档的职责边界:**安全规则写在 _SYSTEM_PROMPT 里,不靠这里**。
# 这里只决定"走哪条通路"(要不要走 FAQ 快路、先查哪一路)。
# 所以分错的代价是有限的 —— 事务题被误判成概念题,顶多多调一次大模型,
# 答案仍受提示词第②条(事务类不许猜)保护。因此判定写得**宽松**些更好:
# 宁可多查一次资料,不要漏掉事务题。
#
# 【事务档·强】毫无歧义的课程事务词。刻意**只收多字短语**:
# 单字「交」「分」「时间」都不能收 ——「交流电」含"交"、「分压」含"分"、
# 「时间常数」含"时间",收单字会把概念题大批误判成事务题。
_ADMIN_HARD = re.compile("|".join(re.escape(w) for w in (
    "提交", "补交", "截止", "deadline", "逾期", "迟交", "没交", "漏交", "未交",
    "成绩", "得分", "评分", "平时分", "记分", "挂科", "及格",
    "考试", "小测", "期中考", "期末考", "考勤", "签到", "请假", "缺勤",
    "雨课堂", "学委", "课代表", "调课", "补课", "点名", "名单",
)))

# 【概念档】明确的学科提问标志。它**优先于事务档·弱**,用来救这类句子:
#   「作业里的叠加定理怎么理解」→ 含"作业"(事务弱信号),但问的是定理 → 概念题
# 但**不能盖过事务档·强**:「考试会考叠加定理吗」问的是考试安排,必须走事务。
_CONCEPT_MARK = re.compile("|".join(re.escape(w) for w in (
    "什么是", "是什么意思", "是啥", "的定义", "定义", "概念",
    "原理", "定理", "定律", "推论", "物理意义", "作用", "意义", "应用",
    "为什么", "为何", "怎么理解", "如何理解", "怎么推导", "推导", "证明",
    "怎么判断", "怎么区分", "讲解一下", "解释一下", "举例",
)))

# 【事务档·弱】作业/时间轴这类"看着像事务"的信号。
# 单独出现算事务,但被 _CONCEPT_MARK 覆盖(见上面两条)。
_ADMIN_SOFT = re.compile(
    "|".join(re.escape(w) for w in (
        "交作业", "要交", "得交", "怎么交", "交给谁", "交到哪", "交去哪",
        "什么时候交", "哪天交", "几号交", "几点交",
        "报告模板", "格式要求", "字数要求", "作业要求", "布置", "下载",
        "周一", "周二", "周三", "周四", "周五", "周六", "周日", "周天", "星期",
        "几号", "几点", "第几周",
    ))
    # 作业轴:问"作业要不要交 / 写在哪 / 什么格式"这类。
    # 只认「作业」后面 10 字内出现疑问或格式词,避免把"作业里的叠加定理"也吞掉。
    + r"|作业[^,，。！!？?\n]{0,10}(?:吗|嘛|呢|几|哪|怎么|什么|要不|能不|可以"
      r"|时间|截止|交|写|格式|要求)"
    # "要…吗"轴(如「思维导图要画吗」「这个要交吗」)。
    # 它本身很宽,但 _CONCEPT_MARK 优先级更高,所以
    # 「叠加定理要满足什么条件吗」这种会先被判成概念题,不会被这条吞掉。
    + r"|要[^,，。！!？?\n]{0,4}吗"
)


def _classify(msg: str) -> str:
    """返回 "problem" / "admin" / "concept" 之一。判定顺序见上面各档的注释。"""
    if _is_problem_query(msg):
        return "problem"
    if _ADMIN_HARD.search(msg):
        return "admin"
    if _CONCEPT_MARK.search(msg):
        return "concept"
    if _ADMIN_SOFT.search(msg):
        return "admin"
    return "concept"


