# -*- coding: utf-8 -*-
"""提问分档(`_classify`)的回归测试。

三档的职责(详见 src/handlers/qa.py 的注释):
  - problem:带题号的提问 → 先查资料,FAQ 只兜底
  - admin  :课程事务(交作业/截止/成绩/考试/考勤)→ FAQ 命中就不调大模型
  - concept:学科概念/原理 → 允许大模型用自己的知识讲,并结合库里的作业题

分档只决定**走哪条通路**,安全规则在系统提示词里,所以分错代价有限。
但有两条边界必须钉住,它们是 2026-09-20 反复推敲出来的:

  1. **单字不能当关键词**。「交流电」含"交"、「分压」含"分"、「时间常数」含"时间" ——
     收单字的话概念题会被大批误判成事务题,又回到"什么都答我不确定"。
  2. **概念标志要能救回"作业里的定理"**。「作业里的叠加定理怎么理解」带"作业"
     (事务弱信号),但问的是定理,必须判 concept;而「考试会考叠加定理吗」带"考试"
     (事务强信号),问的是考试安排,必须判 admin。
"""
from src.handlers.qa import _classify


PROBLEM_QUERIES = [
    "电路基础第一章作业的1.36怎么做？",
    "10.46 那题怎么做",
    "第5题的参考答案",
    "题10.46怎么解",
]

ADMIN_QUERIES = [
    # 提交 / 截止(强信号)
    "电路基础理论的作业怎么提交？要交给学委吗？",
    "作业可以补交吗",
    "补交表在哪里",
    "截止到什么时候",
    # 成绩 / 考试(强信号)
    "电路基础期末成绩怎么算",
    "考试可以带计算器吗",
    "考勤怎么算",
    "雨课堂怎么加入电路基础班级",
    # 作业轴(弱信号,但没被概念标志覆盖)
    "这周电路基础有作业吗",
    "作业一定要写在A4纸上吗",
    "老师布置了几道题",
    "思维导图要画吗",
    "周四的课调到哪了",
    # 强信号压过概念标志:问的是考试安排,不是叠加定理本身
    "考试会考叠加定理吗",
]

CONCEPT_QUERIES = [
    "什么是叠加原理",                     # 本次助教反馈的原始问法
    "什么是叠加定理",
    "叠加定理和戴维南定理的区别是什么",
    "为什么功率因数要补偿",
    "基尔霍夫定律怎么理解",
    "RC 电路的时间常数是什么意思",        # 含"时间",不能被当成事务题
    "交流电的有效值怎么算",               # 含"交",不能被当成事务题
    "分压公式的推导过程",
    "作业里的叠加定理怎么理解",           # 含"作业",但问的是定理 → 概念
    "三相电的应用",
    "怎么看懂这个波形",
]


def test_problem_queries():
    for q in PROBLEM_QUERIES:
        assert _classify(q) == "problem", f"{q} → {_classify(q)},应为 problem"


def test_admin_queries():
    for q in ADMIN_QUERIES:
        assert _classify(q) == "admin", f"{q} → {_classify(q)},应为 admin"


def test_concept_queries():
    for q in CONCEPT_QUERIES:
        assert _classify(q) == "concept", f"{q} → {_classify(q)},应为 concept"


def test_default_is_concept_not_admin():
    """全新问法(谁都没预料到的)默认按概念题处理 ——
    事务类的安全性由系统提示词第②条兜底,不靠这个分类器。"""
    assert _classify("这个电路的等效电阻怎么求") == "concept"
    assert _classify("电感和电容有什么区别") == "concept"
