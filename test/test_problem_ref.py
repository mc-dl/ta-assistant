# -*- coding: utf-8 -*-
"""题号识别(`_is_problem_query`)的回归测试。

背景:2026-09-20 学生问「电路基础第一章作业的1.36怎么做？」,FAQ 里那条
「电路基础理论的作业怎么提交？」以 5.61 分(阈值 4.0)命中并**短路掉资料通路**,
学生拿到的是交作业流程 + 一句"这个我不确定",而 1.36 的答案就在知识库里。

修法是:提问带题号 → 先查资料、FAQ 只兜底。这个判定必须**既准又稳**:
  - 漏判(该 True 的判 False)→ 回到老问题,答不出题;
  - 误判(该 False 的判 True)→ 把"怎么交作业""有没有作业"这类本该 FAQ 直接答的问题
    推去查资料,反而变差。
所以这里把两类都钉住,尤其是 `第1次作业`(次数,不是题号)和日期。
"""
from src.handlers.qa import _is_problem_query


PROBLEM_QUERIES = [
    "电路基础第一章作业的1.36怎么做？",       # 本次踩坑的原始问法
    "10.46 那题怎么做",
    "第一章 1.23 的答案",
    "1.23最后是算电还是电费",
    "第5题的参考答案",
    "第 5 题怎么做",
    "题10.46怎么解",
    "第十九章 19.45",
    "电路基础作业第5题的参考答案",
]

NON_PROBLEM_QUERIES = [
    "电路基础理论的作业怎么提交？要交给学委吗？",
    "这周电路基础有作业吗",
    "作业一定要写在A4纸上吗",
    "雨课堂怎么加入电路基础班级",
    "思维导图要画吗",
    "参考答案在哪下载",
    # 补交登记类:"第N次"是作业次数,不是题号 —— 误判会把它推去查资料
    "王小明 20230001 漏交第1次作业",
    "第1次作业没交",
    "第 3 次作业补交",
    # 日期不能被当成 "20.2026" 这种题号
    "2026-09-20 的作业",
    # 数电类与概念题
    "Proteus 在哪下载?",
    "实验报告模板在哪",
    "什么是竞争冒险?",
]


def test_problem_queries_are_detected():
    for q in PROBLEM_QUERIES:
        assert _is_problem_query(q), f"应判为问题目(带题号),但判成了 False:{q}"


def test_non_problem_queries_are_not_detected():
    for q in NON_PROBLEM_QUERIES:
        assert not _is_problem_query(q), f"不该判为问题目,但判成了 True:{q}"
